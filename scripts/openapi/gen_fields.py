"""The comparison table between this library's OpenAI bodies and the official description.

The description is `openai-openapi`, pinned by commit in `fields.json`. Two outputs come from
one run:

- `fields.json` — the field names of each schema this library writes or reads. It is committed,
  so the table is reviewable in a diff and CI needs no network.
- `src/openai/openapi_fields.generated.mbt` — the same table as MoonBit arrays, which the tests
  use to reject a body that carries a key the description does not have.

Usage:

    python3 scripts/openapi/gen_fields.py --spec path/to/openapi.json   # regenerate both
    python3 scripts/openapi/gen_fields.py --check                       # CI: fail if stale
"""

import json
import re
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIELDS = ROOT / "scripts" / "openapi" / "fields.json"
OUT = ROOT / "src" / "openai" / "openapi_fields.generated.mbt"

# MoonBit constant name -> schema in the description.
SCHEMAS = {
    "chat_completion_request": "CreateChatCompletionRequest",
    "chat_message_system": "ChatCompletionRequestSystemMessage",
    "chat_message_user": "ChatCompletionRequestUserMessage",
    "chat_message_assistant": "ChatCompletionRequestAssistantMessage",
    "chat_message_tool": "ChatCompletionRequestToolMessage",
    "chat_completion_tool": "ChatCompletionTool",
    "chat_message_tool_call": "ChatCompletionMessageToolCall",
    "chat_message_function": "FunctionObject",
    "chat_completion_response": "CreateChatCompletionResponse",
    # The choice object is inline in the response, so it is addressed by its path.
    "chat_completion_choice": (
        "CreateChatCompletionResponse",
        "properties",
        "choices",
        "items",
    ),
    "chat_completion_message": "ChatCompletionResponseMessage",
    "embedding_request": "CreateEmbeddingRequest",
    "embedding_response": "CreateEmbeddingResponse",
    "embedding": "Embedding",
    "moderation_request": "CreateModerationRequest",
    "moderation_response": "CreateModerationResponse",
    "speech_request": "CreateSpeechRequest",
    "transcription_request": "CreateTranscriptionRequest",
    "image_request": "CreateImageRequest",
    "image_response": "ImagesResponse",
    "response_request": "CreateResponse",
}


def collect(properties, schema):
    """Field names of a schema, following `$ref`, `allOf`, `oneOf` and `anyOf`."""
    keys = []
    if not isinstance(schema, dict):
        return keys
    for key in schema.get("properties", {}):
        keys.append(key)
    for part in schema.get("allOf", []):
        keys.extend(collect(properties, part))
    for part in schema.get("oneOf", []):
        keys.extend(collect(properties, part))
    for part in schema.get("anyOf", []):
        keys.extend(collect(properties, part))
    ref = schema.get("$ref")
    if ref and ref.startswith("#/components/schemas/"):
        name = ref.rsplit("/", 1)[-1]
        keys.extend(collect(properties, properties.get(name, {})))
    return keys


def build(spec_path):
    spec = json.loads(pathlib.Path(spec_path).read_text(encoding="utf-8"))
    properties = spec["components"]["schemas"]
    table = {}
    for key, entry in SCHEMAS.items():
        node = properties
        name = entry[0] if isinstance(entry, tuple) else entry
        if name not in properties:
            raise SystemExit(f"schema not in the description: {name}")
        node = properties[name]
        if isinstance(entry, tuple):
            for step in entry[1:]:
                node = node[step]
        names = sorted(set(collect(properties, node)))
        if not names:
            raise SystemExit(f"schema has no fields: {name}")
        table[key] = names
    return table


def commit_of(spec_path):
    try:
        out = subprocess.run(
            ["git", "-C", str(pathlib.Path(spec_path).parent), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 - a spec copied without git is still usable
        return "unknown"


def moonbit(table, commit):
    lines = [
        "// Generated by scripts/openapi/gen_fields.py from openai-openapi. DO NOT EDIT.",
        f"// Description commit: {commit}",
        "",
    ]
    for key in table:
        lines.append("///|")
        entry = SCHEMAS[key]
        name = entry[0] if isinstance(entry, tuple) else entry
        lines.append(f"/// The fields the description gives `{name}`.")
        lines.append(
            f"pub let {key}_fields : Array[String] = ["
        )
        for name in table[key]:
            lines.append(f'  "{name}",')
        lines.append("]")
        lines.append("")
    return "\n".join(lines)


def parse_moonbit(text):
    """The arrays in the generated MoonBit file, read back for the staleness check.

    The check compares field names, not bytes: `moon fmt` reflows the arrays, putting a short
    one on a single line, and a table that lists the same fields is not stale.
    """
    table = {}
    pattern = re.compile(
        r"pub let (\w+)_fields : Array\[String\] = \[(.*?)\]",
        re.S,
    )
    for match in pattern.finditer(text):
        table[match.group(1)] = re.findall(r'"([^"]*)"', match.group(2))
    return table


def main():
    args = sys.argv[1:]
    if "--check" in args:
        data = json.loads(FIELDS.read_text(encoding="utf-8"))
        actual = parse_moonbit(OUT.read_text(encoding="utf-8"))
        expected = data["schemas"]
        stale = [key for key in expected if actual.get(key) != expected[key]]
        missing = [key for key in expected if key not in actual]
        if stale or missing:
            print(f"the field table is stale: {sorted(set(stale + missing))}")
            print("run gen_fields.py --spec path/to/openapi.json")
            return 1
        print(f"field table up to date ({len(expected)} schemas)")
        return 0
    if "--spec" in args:
        spec_path = pathlib.Path(args[args.index("--spec") + 1])
        table = build(spec_path)
        commit = commit_of(spec_path)
        FIELDS.write_text(
            json.dumps(
                {"commit": commit, "schemas": table},
                indent=2,
                ensure_ascii=False,
            )
            + "\n",
            encoding="utf-8",
        )
        OUT.write_text(moonbit(table, commit), encoding="utf-8")
        total = sum(len(names) for names in table.values())
        print(f"{len(table)} schemas, {total} fields, commit {commit}")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
